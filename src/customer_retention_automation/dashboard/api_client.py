"""HTTP client for the synthetic retention dashboard."""

import json
import os
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.parse import quote, urlencode
from urllib.request import urlopen

ROUND_IDS = ("day-000", "day-030", "day-060")

DEFAULT_API_URL = "http://localhost:8000"


class RetentionAPIError(RuntimeError):
    """Raised when the retention API cannot be queried."""


def api_base_url() -> str:
    """Return the configured FastAPI URL."""
    return os.getenv("RETENTION_API_URL", DEFAULT_API_URL).rstrip("/")


def get_json(
    path: str,
    params: dict[str, str] | None = None,
) -> Any:
    """Fetch a JSON response from the retention API."""
    url = f"{api_base_url()}{path}"

    if params:
        url = f"{url}?{urlencode(params)}"

    try:
        with urlopen(url, timeout=15) as response:
            return json.load(response)
    except (
        HTTPError,
        URLError,
        TimeoutError,
        OSError,
        ValueError,
    ) as exc:
        raise RetentionAPIError(f"Cannot retrieve {path}: {exc}") from exc


def fetch_round_cases(round_id: str) -> list[dict]:
    """Get all retention cases for one simulation round."""
    if round_id not in ROUND_IDS:
        raise ValueError(f"Unknown simulation round: {round_id}")

    payload = get_json(
        "/retention/round-cases",
        {"round_id": round_id},
    )
    return payload["cases"]


def fetch_all_round_cases() -> list[dict]:
    """Get cases from all three simulation rounds."""
    cases = []

    for round_id in ROUND_IDS:
        cases.extend(fetch_round_cases(round_id))

    return cases


def fetch_round_email_jobs() -> list[dict]:
    """Get email jobs generated by round-specific cases."""
    payload = get_json("/retention/round-email-jobs")
    return payload["jobs"]


def fetch_churn_overview() -> dict:
    """Get the churn simulation's current summary."""
    return get_json("/retention/churn-simulation/overview")


def fetch_churn_customers() -> list[str]:
    """Get customer IDs participating in the simulation."""
    payload = get_json("/retention/churn-simulation/customers")
    return payload["customers"]


def fetch_churn_customer(customer_id: str) -> dict:
    """Get a customer's risk history and churn status."""
    safe_id = quote(customer_id, safe="")
    return get_json(f"/retention/churn-simulation/customers/{safe_id}")
